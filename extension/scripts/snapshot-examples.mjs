// Refreshes the "engine-snapshot" entries in
// converter/transliteration-examples.json from the current engine.
// Entries with any other status (verified, needs-review) are never changed.
//
// Snapshots record what the engine does today so that unintended changes
// are noticed. They are NOT evidence that the output is correct Rohingyalish.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hanifiToLatin, latinToHanifi } from '../../converter/transliterate.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const file = path.join(root, 'converter/transliteration-examples.json');
const data = JSON.parse(await readFile(file, 'utf8'));
const today = new Date().toISOString().slice(0, 10);

// Dictionary spellings (documented example vocabulary) and code-point edge cases.
const WORDS = ['kitab', 'fúl', 'ful', 'faní', 'gór', 'maa', 'zuban', 'eskul', 'nam', 'aijja', 'manúic', 'cánti', 'kolób', 'lofzó', 'ciñçí', 'roóudh', 'ekkán', 'uggwá', 'kessú din'];
const CODEPOINTS = [
  ['10D11 10D1D 10D26', 'tana tone sign (engine approximates with an acute accent and warns)'],
  ['10D11 10D22', 'sakin (engine drops it: no Latin equivalent)'],
  ['10D17 10D1D 10D19 10D1D', 'kinna wa / kinna ya (engine writes w / y, same as wa / ya)'],
  ['10D00 10D1E 10D15', 'carrier letter A before a vowel (silent in Latin)'],
  ['10D00', 'carrier letter A alone (engine writes a)'],
  ['10D31 10D39 10D34 10D37', 'Hanifi digits'],
];

const snapshots = [
  ...WORDS.map((word, i) => {
    const hanifi = latinToHanifi(word).output;
    return {
      id: `snap-word-${String(i + 1).padStart(2, '0')}`,
      hanifi,
      rohingyalish: hanifiToLatin(hanifi).output,
      status: 'engine-snapshot',
      source: `Hanifi generated by latinToHanifi from the dictionary spelling “${word}”; not written by a Hanifi writer.`,
      warnings: hanifiToLatin(hanifi).warnings,
      recorded: today,
    };
  }),
  ...CODEPOINTS.map(([cps, note], i) => {
    const hanifi = String.fromCodePoint(...cps.split(' ').map(h => parseInt(h, 16)));
    return {
      id: `snap-cp-${String(i + 1).padStart(2, '0')}`,
      hanifi,
      rohingyalish: hanifiToLatin(hanifi).output,
      status: 'engine-snapshot',
      source: `Code points ${cps.split(' ').map(c => `U+${c}`).join(' ')}: ${note}.`,
      warnings: hanifiToLatin(hanifi).warnings,
      recorded: today,
    };
  }),
];

data.examples = [...data.examples.filter(e => e.status !== 'engine-snapshot'), ...snapshots];
await writeFile(file, JSON.stringify(data, null, 2) + '\n');
console.log(`Wrote ${snapshots.length} engine snapshots (${data.examples.length - snapshots.length} reviewed/proposed entries kept).`);
